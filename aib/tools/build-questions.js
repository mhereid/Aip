// Converts the AIB-C01 question bank (zghanw/aws-ai-business-strategist, MIT) into aib/questions.js.
// Usage: node aib/tools/build-questions.js /path/to/aws-ai-business-strategist
// Source files are evaluated in an isolated VM context that exposes only `window`.
const vm = require('vm'), fs = require('fs'), path = require('path');
const src = process.argv[2];
if (!src) { console.error('usage: node build-questions.js <source repo dir>'); process.exit(1); }
const ctx = { window: {} }; vm.createContext(ctx);
for (const f of ['d1.js', 'd2.js', 'd3.js', 'd4.js']) vm.runInContext(fs.readFileSync(path.join(src, 'data', f), 'utf8'), ctx, { filename: f });
const DOMAINS = { 1: 'AI Fundamentals and Literacy', 2: 'AI Strategy and Business Value Creation', 3: 'AI Governance and Responsible AI Leadership', 4: 'Business Readiness, Leadership, and AI Transformation' };
const L = i => String.fromCharCode(65 + i);
// Option ids are the letter of the option's position in the source file, so they never change when
// options are shuffled for display. `answer` holds those ids.
const out = ctx.window.QUESTIONS.map((q, n) => ({
  n: n + 1, id: q.id, domain: q.d, question: q.q,
  options: q.o.map((text, i) => ({ id: L(i), text, why: q.r[i] })),
  answer: q.a.map(L)
}));
const header = '// AIB-C01 question bank. Generated by aib/tools/build-questions.js; do not edit by hand.\n' +
  '// Questions: Copyright (c) 2026 zghanw, MIT License. https://github.com/zghanw/aws-ai-business-strategist\n' +
  '// See aib/LICENSE-questions.txt.\n';
fs.writeFileSync(path.join(__dirname, '..', 'questions.js'), header + 'window.AIB_DOMAINS=' + JSON.stringify(DOMAINS) + ';\nwindow.AIB_QUESTIONS=' + JSON.stringify(out) + ';\n');
console.log('wrote ' + out.length + ' questions');
